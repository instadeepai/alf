"""BoTorch test function dataset adapter for domain-neutral testing.

This module provides adapters to use BoTorch's synthetic test functions
(e.g., Branin, Hartmann, Ackley) with ALF's dataset interface. This enables
domain-agnostic testing and validation of optimization algorithms with known
ground truth optima.
"""

from typing import Literal

import numpy as np
import torch
from alf_core import BaseDatasetConfig, Candidate, LabelledCandidates, Modality
from alf_core.dataset.base_dataset import BaseDataset
from botorch.test_functions import (
    DTLZ2,
    ZDT1,
    Ackley,
    Branin,
    BraninCurrin,
    Hartmann,
    Rosenbrock,
)
from botorch.test_functions.base import BaseTestProblem

# Mapping of function names to BoTorch test function classes
TEST_FUNCTIONS = {
    "branin": Branin,
    "hartmann3": lambda: Hartmann(dim=3),
    "hartmann6": lambda: Hartmann(dim=6),
    "ackley": Ackley,
    "rosenbrock": Rosenbrock,
    "branincurrin": BraninCurrin,
    "dtlz2": DTLZ2,
    "zdt1": ZDT1,
}

FunctionName = Literal[
    "branin",
    "hartmann3",
    "hartmann6",
    "ackley",
    "rosenbrock",
    "branincurrin",
    "dtlz2",
    "zdt1",
]


class BoTorchSyntheticDataset(BaseDataset):
    """Dataset adapter for BoTorch synthetic test functions.

    This adapter allows using BoTorch's synthetic test functions (with known optima)
    within ALF's framework. The dataset is generated by random sampling within the
    function's bounds, and candidates are stored as continuous tensors in the
    TABULAR modality.

    Attributes:
        test_fn: The BoTorch test function instance.
        bounds: The input bounds for the test function [(lower, upper), ...].
        dim: Dimensionality of the input space.
        noise_std: Standard deviation of Gaussian noise added to evaluations.
        n_initial_samples: Number of random samples to generate for the dataset.
        true_optimum: Known optimal value (if available).

    Example:
        >>> config = BaseDatasetConfig(
        ...     name="branin",
        ...     modality=Modality.TABULAR,
        ...     seed=42,
        ...     train_ratio=0.1,
        ...     validation_frac=0.2,
        ...     test_ratio=0.1,
        ...     split_type="random"
        ... )
        >>> dataset = BoTorchSyntheticDataset(
        ...     config=config,
        ...     function_name="branin",
        ...     noise_std=0.1,
        ...     n_initial_samples=1000
        ... )
        >>> dataset.setup()
        >>> print(f"Train size: {len(dataset.train_dataset)}")
    """

    def __init__(
        self,
        config: BaseDatasetConfig,
        function_name: FunctionName = "branin",
        dim: int | None = None,
        noise_std: float = 0.0,
        n_initial_samples: int = 1000,
        negate: bool = True,
    ) -> None:
        """Initialize the BoTorch synthetic dataset.

        Args:
            config: Configuration for the base dataset (splits, seed, etc.).
            function_name: Name of the BoTorch test function to use.
            dim: Dimensionality for functions that support variable dimensions
                (e.g., Ackley, Rosenbrock). Ignored for fixed-dimension functions.
            noise_std: Standard deviation of Gaussian noise to add to function
                evaluations (default: 0.0 for noiseless).
            n_initial_samples: Number of random samples to generate for the
                initial dataset pool.
            negate: Whether to negate the function values (default: True).
                Most BoTorch test functions are minimization problems, but ALF
                typically maximizes. Set to True to convert min -> max.

        Raises:
            ValueError: If modality is not TABULAR, function_name is unknown,
                or dim is missing for variable-dimension functions.
        """
        # Ensure modality is TABULAR for continuous optimization
        if config.modality != Modality.TABULAR:
            raise ValueError(
                f"BoTorch synthetic datasets require modality=TABULAR, got {config.modality}"
            )

        super().__init__(config)

        self.function_name = function_name
        self.noise_std = noise_std
        self.n_initial_samples = n_initial_samples
        self.negate = negate

        # Initialize test function
        if function_name not in TEST_FUNCTIONS:
            raise ValueError(
                f"Unknown function: {function_name}. Available: {list(TEST_FUNCTIONS.keys())}"
            )

        # Create test function instance
        fn_class = TEST_FUNCTIONS[function_name]
        if function_name in ["ackley", "rosenbrock", "dtlz2", "zdt1"]:
            # Variable-dimension functions
            if dim is None:
                raise ValueError(f"Must specify 'dim' for function '{function_name}'")
            self.test_fn: BaseTestProblem = fn_class(dim=dim)
        elif function_name in ["hartmann3", "hartmann6"]:
            # Fixed-dimension functions (handled by lambda)
            self.test_fn = fn_class()
        else:
            # Fixed-dimension functions
            self.test_fn = fn_class()

        self.dim = self.test_fn.dim
        self.bounds = self.test_fn.bounds.numpy()  # Shape: (2, dim)
        self.true_optimum = getattr(self.test_fn, "_optimal_value", None)
        if self.true_optimum is not None and self.negate:
            self.true_optimum = -self.true_optimum

    def load_dataset(self) -> LabelledCandidates:
        """Load the synthetic dataset by random sampling.

        Generates random samples within the function's bounds and evaluates
        them using the test function.

        Returns:
            LabelledCandidates with randomly sampled points and their function values.
        """
        # Generate random samples within bounds
        lower_bounds = self.bounds[0]
        upper_bounds = self.bounds[1]

        X = self.rng.uniform(
            low=lower_bounds,
            high=upper_bounds,
            size=(self.n_initial_samples, self.dim),
        )

        # Evaluate test function
        X_torch = torch.from_numpy(X).float()
        y = self.test_fn(X_torch).numpy()

        # Add noise if specified
        if self.noise_std > 0:
            noise = self.rng.normal(0, self.noise_std, size=y.shape)
            y = y + noise

        # Negate for maximization (BoTorch test functions are minimization)
        if self.negate:
            y = -y

        # Convert to Candidates (store tensors as data in TABULAR modality)
        candidates = [Candidate(data=x, modality=Modality.TABULAR, features=None) for x in X]

        return LabelledCandidates(candidates=candidates, labels=y)

    def query(self, candidates: list[Candidate]) -> LabelledCandidates:
        """Evaluate the test function on the given candidates.

        This acts as an "oracle" that can evaluate arbitrary candidates
        on the test function.

        Args:
            candidates: List of Candidate objects with continuous data (numpy arrays).

        Returns:
            Candidates paired with their function values.
        """
        # Extract data from candidates
        X = np.array([cand.data for cand in candidates])
        X_torch = torch.from_numpy(X).float()

        # Evaluate test function
        y = self.test_fn(X_torch).numpy()

        # Add noise if specified
        if self.noise_std > 0:
            noise = self.rng.normal(0, self.noise_std, size=y.shape)
            y = y + noise

        # Negate for maximization
        if self.negate:
            y = -y

        return LabelledCandidates(candidates=candidates, labels=y)

    def set_metadata(self) -> None:
        """Set metadata for the synthetic dataset."""
        self.metadata = {
            "function_name": self.function_name,
            "dim": self.dim,
            "bounds": self.bounds.tolist(),
            "noise_std": self.noise_std,
            "true_optimum": self.true_optimum,
            "negate": self.negate,
            "n_initial_samples": self.n_initial_samples,
        }
